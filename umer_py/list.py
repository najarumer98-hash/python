# append
marks = [50 , 60 , 70 , 80 , 90 , 100]
marks.append(110)
print(marks)

# insert value
marks.insert(2,75)
print(marks)

# sort in ascending order
marks.sort()
print(marks)

# descending order
marks.sort(reverse=True)
print(marks)

# reverse
marks.reverse()
print(marks)

# remove
marks.remove(50)
print(marks)

# pop
marks.pop(2)
print(marks)

# clear
marks.clear()
print(marks)

# copy
marks.copy()
print(marks)